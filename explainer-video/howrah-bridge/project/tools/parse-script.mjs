// Parses ../SCRIPT_BN.md -> src/script.generated.ts (id, bg, type, photo, vo)
import fs from 'node:fs';
import path from 'node:path';
import {fileURLToPath} from 'node:url';
const here = path.dirname(fileURLToPath(import.meta.url));
const md = fs.readFileSync(path.join(here, '..', '..', 'SCRIPT_BN.md'), 'utf8');
const scenes = [];
let cur = null;
for (const line of md.split('\n')) {
  const h = line.match(/^### (S\d\d)\b/);
  if (h) { cur = {id: h[1], bg: 'paper', type: '', photo: null, vo: ''}; scenes.push(cur); continue; }
  if (line.startsWith('## ') || line.startsWith('### ')) { cur = null; continue; }
  if (!cur) continue;
  let m;
  if ((m = line.match(/^- \*\*bg:\*\* `([a-z-]+)`/))) cur.bg = m[1];
  if ((m = line.match(/^- \*\*type:\*\* (.+)$/))) cur.type = m[1].trim();
  if ((m = line.match(/^- \*\*photo:\*\* (P\d\d)/))) cur.photo = m[1];
  // ✂ marks cuttable lines in the script; the markers themselves are never spoken
  if ((m = line.match(/^- \*\*vo:\*\* (.+)$/))) cur.vo = m[1].replace(/✂/g, '').replace(/\s+/g, ' ').trim();
}
const bad = scenes.filter((s) => !s.vo);
if (bad.length) { console.error('Scenes without vo:', bad.map((s) => s.id)); process.exit(1); }
const bgs = new Set(['night', 'night-xs', 'paper', 'paper-xs', 'archive']);
const badBg = scenes.filter((s) => !bgs.has(s.bg));
if (badBg.length) { console.error('Unknown bg:', badBg.map((s) => `${s.id}:${s.bg}`)); process.exit(1); }
const out = `// AUTO-GENERATED by tools/parse-script.mjs from SCRIPT_BN.md — do not edit by hand.
export type Bg = 'night' | 'night-xs' | 'paper' | 'paper-xs' | 'archive';
export type ScriptScene = {id: string; bg: Bg; type: string; photo: string | null; vo: string};
export const SCRIPT: ScriptScene[] = ${JSON.stringify(scenes, null, 2)};
`;
fs.writeFileSync(path.join(here, '..', 'src', 'script.generated.ts'), out);
const words = scenes.reduce((a, s) => a + s.vo.split(/\s+/).length, 0);
console.log(`Parsed ${scenes.length} scenes, ${words} words`);
